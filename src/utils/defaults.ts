/**
 * Returns the default Chart of Accounts Code mapped to a specific Case / Charity Category
 */
export function getDefaultAssistanceAccountCode(category: string): string {
  const cat = (category || '').toLowerCase();
  if (cat.includes('med')) return '5010'; // Medical
  if (cat.includes('wed')) return '5020'; // Wedding
  if (cat.includes('edu')) return '5030'; // Education
  if (cat.includes('food') || cat.includes('ration')) return '5040'; // Food Aid
  if (cat.includes('orphan') || cat.includes('destitute') || cat.includes('widow')) return '5045'; // Orphan
  if (cat.includes('house') || cat.includes('shelter') || cat.includes('maintenance')) return '5050'; // House Maintenance
  if (cat.includes('masjid') || cat.includes('mosque') || cat.includes('community')) return '5060'; // Masjid
  if (cat.includes('funeral') || cat.includes('death') || cat.includes('janazah') || cat.includes('burial')) return '5080'; // Funeral
  if (cat.includes('debt') || cat.includes('repatriation') || cat.includes('gharimeen')) return '5075'; // Debt Relief
  if (cat.includes('emergency')) return '5070'; // Emergency Relief
  return '5090'; // Other
}

